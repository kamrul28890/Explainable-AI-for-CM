# ------------------------------------------------------------------ helpers --

def tb(slide, x, y, w, h, align=PP_ALIGN.LEFT):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.paragraphs[0].alignment = align
    return tf


def run(p, text, size=14, color=INK, bold=False, font=SANS, italic=False):
    r = p.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.color.rgb = color
    r.font.bold = bold
    r.font.italic = italic
    r.font.name = font
    return r


def para(tf, text="", size=14, color=INK, bold=False, font=SANS,
         space_before=0, space_after=6, first=False, italic=False):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.space_before = Pt(space_before)
    p.space_after = Pt(space_after)
    if text:
        run(p, text, size, color, bold, font, italic)
    return p


def rect(slide, x, y, w, h, fill=None, line=None, line_w=1.0):
    s = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    if fill is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(line_w)
    s.shadow.inherit = False
    return s


def blank(prs):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    bg = s.background.fill
    bg.solid()
    bg.fore_color.rgb = PAPER
    return s


def header(slide, eyebrow, title, sub=None):
    """Standard slide head: small coloured eyebrow, title, optional standfirst."""
    tf = tb(slide, M, TOP, W - 2 * M, Inches(0.3))
    para(tf, eyebrow.upper(), 11, ACCENT, bold=True, first=True, space_after=2)

    tf2 = tb(slide, M, TOP + Inches(0.3), W - 2 * M, Inches(0.6))
    para(tf2, title, 27, INK, bold=True, first=True, space_after=0)

    y = TOP + Inches(1.02)
    if sub:
        tf3 = tb(slide, M, y, W - 2 * M - Inches(0.4), Inches(0.4))
        para(tf3, sub, 14, SOFT, first=True)
        y += Inches(0.5)
    rect(slide, M, y, W - 2 * M, Emu(9525), fill=RULE)
    return y + Inches(0.22)


def footer(slide, text, num):
    tf = tb(slide, M, H - Inches(0.45), W - 2 * M - Inches(0.6), Inches(0.3))
    para(tf, text, 9.5, FAINT, first=True)
    tf2 = tb(slide, W - M - Inches(0.5), H - Inches(0.45), Inches(0.5), Inches(0.3),
             align=PP_ALIGN.RIGHT)
    para(tf2, str(num), 9.5, FAINT, first=True)


def bullets(slide, x, y, w, items, size=14, gap=9):
    tf = tb(slide, x, y, w, Inches(0.4))
    for i, item in enumerate(items):
        if isinstance(item, tuple):
            lead, rest = item
        else:
            lead, rest = None, item
        p = para(tf, "", size, INK, first=(i == 0), space_after=gap)
        run(p, "— ", size, ACCENT, bold=True)
        if lead:
            run(p, lead, size, INK, bold=True)
            run(p, rest, size, SOFT)
        else:
            run(p, rest, size, SOFT)
    return tf


def statbox(slide, x, y, w, h, value, label, note=None, tone="neutral"):
    col = {"neutral": ACCENT, "bad": SIGNAL, "good": GOOD}[tone]
    bg = {"neutral": SHADE, "bad": SIGNAL_BG, "good": SHADE}[tone]
    rect(slide, x, y, w, h, fill=bg, line=RULE)
    tf = tb(slide, x + Inches(0.16), y + Inches(0.12), w - Inches(0.3), h)
    para(tf, value, 26, col, bold=True, font=MONO, first=True, space_after=1)
    para(tf, label, 11.5, INK, bold=True, space_after=1)
    if note:
        para(tf, note, 9.5, FAINT, font=MONO)


def table(slide, x, y, w, headers, rows, col_w=None, flag_rows=(), size=11.5):
    n_rows, n_cols = len(rows) + 1, len(headers)
    h = Inches(0.34) * n_rows
    shape = slide.shapes.add_table(n_rows, n_cols, x, y, w, h)
    t = shape.table
    if col_w:
        total = sum(col_w)
        for i, cw in enumerate(col_w):
            t.columns[i].width = Emu(int(w * cw / total))

    for c, htxt in enumerate(headers):
        cell = t.cell(0, c)
        cell.text = ""
        cell.fill.solid()
        cell.fill.fore_color.rgb = INK
        cell.vertical_anchor = MSO_ANCHOR.MIDDLE
        cell.margin_left = cell.margin_right = Inches(0.08)
        p = cell.text_frame.paragraphs[0]
        p.alignment = PP_ALIGN.LEFT if c == 0 else PP_ALIGN.RIGHT
        run(p, htxt, 11, PAPER, bold=True)

    for r, rowvals in enumerate(rows, start=1):
        flag = (r - 1) in flag_rows
        for c, val in enumerate(rowvals):
            cell = t.cell(r, c)
            cell.text = ""
            cell.fill.solid()
            cell.fill.fore_color.rgb = SIGNAL_BG if flag else (
                SHADE if r % 2 == 0 else PAPER)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.margin_left = cell.margin_right = Inches(0.08)
            p = cell.text_frame.paragraphs[0]
            p.alignment = PP_ALIGN.LEFT if c == 0 else PP_ALIGN.RIGHT
            run(p, str(val), size,
                SIGNAL if flag else INK,
                bold=flag and c == 0,
                font=MONO if c > 0 else SANS)
    return shape


def note(slide, x, y, w, label, text, tone="accent"):
    col = ACCENT if tone == "accent" else SIGNAL
    bg = ACCENT_BG if tone == "accent" else SIGNAL_BG
    h = Inches(1.05)
    rect(slide, x, y, w, h, fill=bg)
    rect(slide, x, y, Inches(0.05), h, fill=col)
    tf = tb(slide, x + Inches(0.22), y + Inches(0.13), w - Inches(0.42), h)
    para(tf, label.upper(), 10, col, bold=True, first=True, space_after=3)
    para(tf, text, 13, INK)


def picture(slide, name, x, y, max_w, max_h):
    from PIL import Image
    path = ASSETS / name
    if not path.exists():
        rect(slide, x, y, max_w, max_h, fill=SHADE, line=RULE)
        tf = tb(slide, x + Inches(0.2), y + max_h / 2, max_w - Inches(0.4), Inches(0.4))
        para(tf, f"[missing asset: {name}]", 12, FAINT, first=True)
        return
    iw, ih = Image.open(path).size
    scale = min(max_w / iw, max_h / ih)
    w_, h_ = int(iw * scale), int(ih * scale)
    slide.shapes.add_picture(str(path), int(x + (max_w - w_) / 2),
                             int(y + (max_h - h_) / 2), w_, h_)


def pipeline(slide, x, y, w, steps, tone=ACCENT):
    """Native shapes so the diagram stays editable in PowerPoint."""
    n = len(steps)
    gap = Inches(0.14)
    bw = (w - gap * (n - 1)) / n
    bh = Inches(0.95)
    for i, (num, label) in enumerate(steps):
        bx = x + i * (bw + gap)
        rect(slide, bx, y, bw, bh, fill=SHADE, line=RULE)
        rect(slide, bx, y, bw, Inches(0.05), fill=tone)
        tf = tb(slide, bx + Inches(0.1), y + Inches(0.17), bw - Inches(0.2), bh)
        para(tf, num, 9.5, tone, bold=True, font=MONO, first=True, space_after=2)
        para(tf, label, 11, INK, bold=True)
        if i < n - 1:
            ar = slide.shapes.add_shape(
                MSO_SHAPE.RIGHT_ARROW, bx + bw + Emu(int(gap * 0.12)),
                y + bh / 2 - Inches(0.06), Emu(int(gap * 0.76)), Inches(0.12))
            ar.fill.solid()
            ar.fill.fore_color.rgb = RULE
            ar.line.fill.background()
            ar.shadow.inherit = False


# ------------------------------------------------------------------- data ----

def read(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def stage4_status() -> tuple[int, int, str]:
    rows = read(S2 / "results" / "descriptive_accuracy_qwen7b-4bit.csv")
    regions = read(S2 / "results" / "regions_qwen7b-4bit.csv")
    total = sum(1 for r in regions if r.get("source") == "model" and r.get("region"))
    if not rows:
        return 0, total, "not started"
    if len(rows) >= total:
        return len(rows), total, "complete"
    return len(rows), total, "in progress"


